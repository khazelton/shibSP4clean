#!/usr/bin/env python3
"""Generate the hub's agent beans from a flat agent list.

A stand-in for the "loader bean" Scott described on the dev list: advanced, shared
configuration stays in XML templates (one per group of agents, a one-time cost), and the
day-to-day facts about each agent (id, allowed addresses, the usernames that may
authenticate as it, an owner) live in a flat file an operator or IGA tool can maintain.

  input:  hub/agents/agents.csv              one row per agent
          hub/agents/templates/<group>.xml   bean template per group (string.Template, ${...})
          hub/htpasswd/agents.htpasswd       optional; only used to report credential sources
  output: hub/agents/generated/agents-generated.xml
          bind-mounted into the hub and listed in shibboleth.sp.AgentResolverResources
          (hub/entrypoint.sh) next to conf/sp/agents.xml

  ./gen-agents-xml.py            validate and write the output if it changed
  ./gen-agents-xml.py --check    validate only; exit 1 if the output is out of date
  ./gen-agents-xml.py --reload   write, then reload the hub's AgentResolverService
                                 (otherwise the hub polls every sp.service.agents.checkInterval)

Exit codes: 0 ok, 1 output out of date (--check), 2 validation or reload error.
Standard library only.
"""
import csv
import ipaddress
import re
import string
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
AGENTS_DIR = HERE / "hub" / "agents"
CSV_PATH = AGENTS_DIR / "agents.csv"
TEMPLATES = AGENTS_DIR / "templates"
OUT_PATH = AGENTS_DIR / "generated" / "agents-generated.xml"
HTPASSWD = HERE / "hub" / "htpasswd" / "agents.htpasswd"

# agent ids and usernames end up inside XML attributes and SpEL string literals
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:@-]*$")
COLUMNS = ["agent_id", "group", "allowed_ranges", "usernames", "owner"]

HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
GENERATED by deploy/gen-agents-xml.py from hub/agents/agents.csv. Do not edit by hand.
Loaded by the hub's AgentResolverService alongside conf/sp/agents.xml.
-->
<beans xmlns="http://www.springframework.org/schema/beans"
       xmlns:p="http://www.springframework.org/schema/p"
       xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
       xsi:schemaLocation="http://www.springframework.org/schema/beans http://www.springframework.org/schema/beans/spring-beans.xsd"
       default-init-method="initialize"
       default-destroy-method="destroy">

"""
FOOTER = "</beans>\n"


def xml_comment(text):
    # "--" is illegal inside an XML comment
    return text.replace("--", "- -")


def spel_list(items):
    return "#{ {" + ", ".join(f"'{i}'" for i in items) + "} }"


def load_htpasswd_users():
    if not HTPASSWD.exists():
        return set()
    users = set()
    for line in HTPASSWD.read_text().splitlines():
        if line and not line.startswith("#") and ":" in line:
            users.add(line.split(":", 1)[0])
    return users


def read_rows():
    lines = [l for l in CSV_PATH.read_text().splitlines() if l.strip() and not l.lstrip().startswith("#")]
    reader = csv.DictReader(lines)
    if reader.fieldnames != COLUMNS:
        raise ValueError(f"{CSV_PATH.name}: header must be {','.join(COLUMNS)}, got {reader.fieldnames}")
    # line numbers refer to the filtered rows; good enough for a short list
    return list(reader)


def validate(rows):
    errors, agents = [], []
    ids, owner_of = set(), {}
    for n, r in enumerate(rows, 1):
        where = f"row {n} ({r.get('agent_id') or '?'})"
        aid = (r["agent_id"] or "").strip()
        group = (r["group"] or "").strip()
        ranges = (r["allowed_ranges"] or "").split()
        usernames = (r["usernames"] or "").split()
        owner = (r["owner"] or "").strip()

        if not NAME_RE.match(aid):
            errors.append(f"{where}: invalid agent_id {aid!r}")
        elif aid in ids:
            errors.append(f"{where}: duplicate agent_id {aid!r}")
        ids.add(aid)

        if not (TEMPLATES / f"{group}.xml").is_file():
            errors.append(f"{where}: no template hub/agents/templates/{group}.xml for group {group!r}")

        if not ranges:
            errors.append(f"{where}: allowed_ranges is empty (the hub would accept the agent from anywhere)")
        for cidr in ranges:
            try:
                ipaddress.ip_network(cidr, strict=False)
            except ValueError:
                errors.append(f"{where}: invalid address range {cidr!r}")

        if len(set(usernames)) != len(usernames):
            errors.append(f"{where}: repeated username")
        # the hub resolves the agent *from* the username, so each one must map to one agent;
        # with no usernames, the agent id itself is the username
        for u in usernames or [aid]:
            if not NAME_RE.match(u):
                errors.append(f"{where}: invalid username {u!r}")
            elif u in owner_of and owner_of[u] != aid:
                errors.append(f"{where}: username {u!r} already belongs to agent {owner_of[u]!r}")
            owner_of[u] = aid

        agents.append(dict(id=aid, group=group, ranges=ranges, usernames=usernames, owner=owner))

    # an agent id must not collide with another agent's username either
    for a in agents:
        if a["id"] in owner_of and owner_of[a["id"]] != a["id"]:
            errors.append(f"agent_id {a['id']!r} is also a username of agent {owner_of[a['id']]!r}")
    return agents, errors


def render(agents):
    parts = [HEADER]
    for a in agents:
        tmpl = string.Template((TEMPLATES / f"{a['group']}.xml").read_text())
        comment = a["id"] + (f" | owner: {a['owner']}" if a["owner"] else "") + f" | group: {a['group']}"
        usernames_attr = f'\n          p:usernames="{spel_list(a["usernames"])}"' if a["usernames"] else ""
        parts.append(tmpl.substitute(
            id=a["id"],
            comment=xml_comment(comment),
            usernames_attr=usernames_attr,
            ranges=spel_list(a["ranges"]),
            owner=a["owner"],
        ).rstrip() + "\n\n")
    parts.append(FOOTER)
    return "".join(parts)


def report(agents):
    ht = load_htpasswd_users()
    for a in agents:
        names = a["usernames"] or [a["id"]]
        srcs = ", ".join(f"{u} ({'htpasswd' if u in ht else 'LDAP/other'})" for u in names)
        print(f"  {a['id']:<28} {' '.join(a['ranges']):<18} {srcs}")


def reload_hub():
    cmd = ["docker", "exec", "sp4-hub", "/opt/shibboleth-idp/bin/reload-service.sh",
           "-u", "http://localhost:8080/idp", "-id", "shibboleth.sp.AgentResolverService"]
    res = subprocess.run(cmd, capture_output=True, text=True)
    out = (res.stdout + res.stderr).strip().splitlines()
    print("reload:", out[-1] if out else f"exit {res.returncode}")
    return res.returncode == 0 and any("reloaded" in l for l in out)


def main(argv):
    check = "--check" in argv
    reload = "--reload" in argv
    try:
        agents, errors = validate(read_rows())
    except (OSError, ValueError, KeyError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        return 2

    text = render(agents)
    current = OUT_PATH.read_text() if OUT_PATH.exists() else None
    print(f"{len(agents)} agent(s) from {CSV_PATH.relative_to(HERE)}:")
    report(agents)

    if check:
        if text != current:
            print(f"out of date: {OUT_PATH.relative_to(HERE)}")
            return 1
        print("up to date")
        return 0

    if text != current:
        OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        tmp = OUT_PATH.with_suffix(".tmp")
        tmp.write_text(text)
        tmp.replace(OUT_PATH)  # atomic; the hub bind-mounts the directory
        print(f"wrote {OUT_PATH.relative_to(HERE)}")
    else:
        print("unchanged")

    if reload and not reload_hub():
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
